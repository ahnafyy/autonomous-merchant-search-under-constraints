def render_ucp_cost_sensitivity_table(results: dict[str, Any]) -> str:
    """Render complete-cost multipliers without implying observed billing."""
    sensitivity = results["ucp_cost_sensitivity"]
    lines = [
        "% Generated by paperkit. Do not edit.",
        r"\begin{tabular}{@{}rrrrrl@{}}",
        r"\toprule",
        r"Cost multiple & Cost & Comparator & Difference & 95\% CI & Status \\",
        r"\midrule",
    ]
    for row in sensitivity["cost_results"]:
        comparison = row["adaptive_vs_search_all"]
        scenario = str(row["cost_scenario"])
        multiple = scenario.rsplit("_x", maxsplit=1)[-1]
        if comparison["favors_treatment"]:
            status = "Adaptive improvement"
        elif comparison["ci_lower"] > 0:
            status = "Search-all improvement"
        else:
            status = "No reliable improvement"
        lines.append(
            f"{multiple}$\\times$ & \\${row['inspection_cost_usd']:.5f} & "
            "search all & "
            f"{comparison['mean_difference']:+.4f} & "
            f"[{comparison['ci_lower']:.4f}, {comparison['ci_upper']:.4f}] & {status} \\\\"
        )
    lines.extend([r"\bottomrule", r"\end{tabular}"])
    return "\n".join(lines) + "\n"


def render_source_table(results: dict[str, Any]) -> str:
    """Render separate source roles rather than pooling incompatible observations."""
    shopify = results["shopify_global_catalog"]
    ucp = results["ucp_direct_panels"]
    deck_count = shopify.get("product_deck_count", 0)
    seller_count = shopify.get("seller_card_count", 0)
    included_dates = ucp.get("included_lifecycle_dates", [])
    excluded_dates = ucp.get("excluded_dates", {})
    cost_overlay = ucp.get("cost_overlay", {})
    probe_calls = cost_overlay.get("total_merchant_probe_calls", 0)
    scenario_count = len(cost_overlay.get("scenarios", []))
    lines = [
        "% Generated by paperkit. Do not edit.",
        r"\begin{tabular}{@{}p{0.24\linewidth}p{0.32\linewidth}p{0.34\linewidth}@{}}",
        r"\toprule",
        r"Source & What it supplies & Reporting role \\",
        r"\midrule",
        "Shopify Global Catalog & "
        f"{deck_count} seller decks; {seller_count} seller cards; one frozen USD snapshot & "
        "Exploratory free-recall Pandora replay; no advantage claim. \\\\",
        "UCP direct merchant panels & "
        f"{len(included_dates)} lifecycle dates; "
        f"{len(excluded_dates)} common-mode dates excluded & "
        f"{probe_calls} merchant probes costed under {scenario_count} declared scenarios; "
        "catalog observability context, not pooled with Shopify decks. \\\\"
    ]
    lines.extend([r"\bottomrule", r"\end{tabular}"])
    return "\n".join(lines) + "\n"
